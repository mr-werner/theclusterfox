"""Builds src/features/ready/data/aftTables.js from the Army's official
AFT score tables (army.mil/aft, "AFT_Scoring_Scales_250601.pdf",
approved 15 May 2025, effective 1 June 2025).

  pdftotext -layout AFT_Scoring_Scales_250601.pdf aft.txt
  python3 scripts/ready/aft-tables.py aft.txt > src/features/ready/data/aftTables.js

Each event keeps, per age group and column ("m" is the male column, which
is also the sex-neutral combat standard; "f" is female), the lowest
(or, for the sprint-drag-carry and run, slowest) result that earns each point value.
"""
import json
import re
import sys

EVENTS = [
    ("mdl", "Max Deadlift", "reps"),
    ("hrp", "Hand-release Push-up", "reps"),
    ("sdc", "Sprint / Drag / Carry", "time"),
    ("plk", "Plank", "hold"),
    ("2mr", "Two-Mile Run", "time"),
]
AGES = ["17-21", "22-26", "27-31", "32-36", "37-41", "42-46", "47-51", "52-56", "57-61", "62+"]


def value(tok, kind):
    if tok == "---":
        return None
    if kind in ("time", "hold"):
        m, s = tok.split(":")
        return int(m) * 60 + int(s)
    return int(tok)


def main(path):
    lines = open(path, encoding="utf8").read().splitlines()
    current = None
    tables = {e[0]: {a: {"m": {}, "f": {}} for a in AGES} for e in EVENTS}
    kinds = {e[0]: e[2] for e in EVENTS}
    for line in lines:
        for eid, title, _ in EVENTS:
            if title in line:
                current = eid
        if "Alternate Events" in line:
            current = None
        if current is None:
            continue
        toks = line.split()
        if len(toks) != 22 or not toks[0].isdigit() or toks[0] != toks[-1]:
            continue
        pts = int(toks[0])
        for i, age in enumerate(AGES):
            for j, col in enumerate(("m", "f")):
                v = value(toks[1 + i * 2 + j], kinds[current])
                if v is not None:
                    tables[current][age][col][pts] = v
    out = {}
    for eid, title, kind in EVENTS:
        out[eid] = {"name": title, "kind": kind, "ages": {}}
        for age in AGES:
            out[eid]["ages"][age] = {
                col: sorted(([p, v] for p, v in tables[eid][age][col].items()), reverse=True)
                for col in ("m", "f")
            }
            for col in ("m", "f"):
                have = {p for p, _ in out[eid]["ages"][age][col]}
                assert {0, 60, 100} <= have, (eid, age, col)
    print("// Generated by scripts/ready/aft-tables.py from the Army's official AFT")
    print("// score tables (approved 15 May 2025, effective 1 June 2025). Do not edit by hand.")
    print("// Each row is [points, result]: the lowest result (fewest reps, or slowest")
    print("// time in seconds) that earns those points. \"m\" is the male column, which")
    print("// is also the sex-neutral combat standard; \"f\" is the female column.")
    print(f"export const AFT_AGES = {json.dumps(AGES)};")
    print(f"export const AFT_TABLES = {json.dumps(out, separators=(',', ':'))};")


main(sys.argv[1])
